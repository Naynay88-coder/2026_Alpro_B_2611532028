# Buat file dengan Perbandungan_nim.py
# Nama variabel ditambah 4 digit nim terakhir contoh: angka_1234
# Program ini menggunakan fungsi input
# Nilai yang dimasukkan akan dikonversi menjadi tipe data integer
# Program operator perbandingan dalam Python

angka1_2028 = int(input("Input angka-1: "))
angka2_2028 = int(input("Input angka-2:"))

# lebih besar dari
hasil_2028 = angka1_2028 > angka2_2028
print("\nOperator lebih besar dari")
print("angka1_2028 > angka2 =", hasil_2028)

# lebih kecil dari
hasil_2028 = angka1_2028 < angka2_2028
print("\nOperator lebih kecil dari")
print("angka1_2028 < angka2 =", hasil_2028)

# lebih besar dari atau sama dengan
hasil_2028 = angka1_2028 >= angka2_2028
print("\nOperator lebih besar dari atau sama dengan")
print("angka1_2028 >= angka2_2028", hasil_2028)

# lebih kecil dari atau sama dengan
hasil_2028 = angka1_2028 <= angka2_2028
print("\nOperator lebih kecil dari atau sama dengan")
print("angka1_2028 <= angka2_2028 =", hasil_2028)

# sama dengan
hasil_2028 = angka1_2028 == angka2_2028
print("\nOperator sama dengan")
print("angka1_2028 == angka2_2028 =", hasil_2028)

# tidak sama dengan
hasil_2028 = angka1_2028 != angka2_2028
print("\nOperator tidak sama dengan")
print("angka1_2028 != angka2_2028 =", hasil_2028)

# tambahan: perbandingan dengan tipe data dalam python
hasil_2028 = 0 < angka1_2028 < 100
