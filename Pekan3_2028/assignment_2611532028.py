# Nama variabel ditambah 4 digit nim terakhir contoh: angka1_1234
# Program ini menggunakan fungsi input()
# Nilai yang dimasukkan akan dikonversi menjadi tipe data integer
# Program operator assignment dalam python

angka1_2028 = int(input("input angka-1: "))
angka2_2028 = int(input("input angka-2:"))

print("\nNilai awal angka1_2028 =", angka1_2028)
print("Nilai angka2_2028 =", angka2_2028)

# Assignment biasa
hasil = angka1_2028
print("\nAssignment biasa (=)")
print("Hasil =", hasil)

# Assignment penambahan
hasil_2028 = angka1_2028
hasil_2028 += angka2_2028
print("\nAssignment penambahan (=+)")
print("Hasil =", hasil_2028)

# Assignment pengurangan
hasil = angka1_2028
hasil = angka2_2028
print("\nAssignment pengurangan")
print("HAsil =", hasil_2028)