# Buat nama file dengan nama nilai_nim.py
# Buat program untuk nested if
# Nama variabel ditambah 4 digit nim terakhir contoh: ipk_2028
# Program ini menggunakan fungsi input ()
# Program konvensi nilai angka menjadi huruf

nilai_2028 = int(input("Inputkan Nilai Angka= "))

if nilai_2028 >= 81:
    print("A")
elif nilai_2028 >= 70:
    print("B")
elif nilai_2028 >= 60:
    print("C")
elif nilai_2028 >= 50:
    print("D")
else:
    print("E")